import type { Property } from "@yenimenzil/types";
import { demoImages } from "./images";

const DAY = 24 * 60 * 60 * 1000;
const now = Date.now();

function daysAgo(n: number, hour = 14, minute = 30): string {
  return new Date(now - n * DAY - ((24 - hour) * 60 - minute) * 60 * 1000).toISOString();
}

let seq = 1000;

function makeListing(
  listing: Omit<
    Property,
    "id" | "referenceCode" | "slug" | "isFavorite" | "images" | "mortgageAvailable"
  > & { images: string[]; mortgageAvailable?: boolean }
): Property {
  seq += 1;
  const ref = `AB${seq}`;
  return {
    ...listing,
    id: `prop-${ref.toLowerCase()}`,
    referenceCode: ref,
    slug: `${listing.dealType}-${listing.propertyType}-${ref.toLowerCase()}`,
    isFavorite: false,
    images: demoImages(listing.images).map((img, i) => ({
      src: img.src,
      alt: img.alt,
      placeholder:
        i === 0
          ? img.src.replace(/w=1400&q=80/, "w=40&q=20&blur=30")
          : undefined
    })),
    pricePerSqm:
      listing.propertyType === "land" || listing.propertyType === "garage"
        ? undefined
        : Math.round(listing.price / listing.areaTotal),
    mortgageAvailable: listing.mortgageAvailable ?? false
  };
}

